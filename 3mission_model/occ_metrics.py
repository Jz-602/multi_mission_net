"""Sparse full-ROI OCC counts; ungenerated cells predict empty, without dense 3D arrays."""
from __future__ import annotations

import itertools
import time

import torch

from occ_head import MatchRows, UniqueRows


def BZYX(xyz):
    return torch.cat((torch.zeros((len(xyz), 1), device=xyz.device, dtype=torch.long), xyz[:, [2, 1, 0]].long()), dim=1)


def CoverageMask(gt_xyz, root_xyz, grid_shape_xyz, b_expand_roots):
    """Check positive leaf reachability by querying only its parent/root neighbors."""
    parents = BZYX(gt_xyz // 4)
    roots = BZYX(root_xyz)
    root_shape = tuple(int(v) // 4 for v in grid_shape_xyz[::-1])
    shape = torch.tensor(root_shape, device=parents.device)
    b_covered = torch.zeros(len(parents), device=parents.device, dtype=torch.bool)
    offsets = itertools.product((-1, 0, 1), repeat=3) if b_expand_roots else [(0, 0, 0)]
    # Sort roots once, then reuse their compact keys for the 27 neighbor queries.
    from occ_head import CoordinateKeys
    unique_rows = UniqueRows(roots, root_shape)
    root_keys = CoordinateKeys(roots[unique_rows], root_shape)
    if root_keys.numel() == 0:
        return b_covered
    for offset in offsets:
        neighbors = parents.clone()
        neighbors[:, 1:] += torch.tensor(offset, device=parents.device)
        b_valid = ((neighbors[:, 1:] >= 0) & (neighbors[:, 1:] < shape)).all(dim=1)
        keys = CoordinateKeys(neighbors, root_shape)
        rows = torch.searchsorted(root_keys, keys)
        safe_rows = rows.clamp(max=root_keys.numel() - 1)
        b_covered |= b_valid & (rows < root_keys.numel()) & (root_keys[safe_rows] == keys)
    return b_covered


@torch.no_grad()
def FrameMetrics(pred_xyz, pred_labels, gt_xyz, gt_labels, grid_shape_xyz,
                 root_xyz=None, kept_root_xyz=None, b_expand_roots=True, *,
                 b_collect_occ_stage_statistics=False, current_points_xyz=None,
                 pc_range=None, expanded_root_xyz=None, target_id=None,
                 b_valid_roi_confirmed=False):
    """Input XYZ grid coordinates share a vehicle-frame ROI; return additive counts.

    True ignore=255 coordinates are excluded. Identical duplicate prediction rows
    count once (first row deterministically wins). GT validity is checked upstream.
    """
    shape = tuple(map(int, grid_shape_xyz[::-1]))
    pred_coords, gt_coords = BZYX(pred_xyz), BZYX(gt_xyz)
    pred_rows, gt_rows = UniqueRows(pred_coords, shape), UniqueRows(gt_coords, shape)
    pred_coords, pred_labels = pred_coords[pred_rows], pred_labels[pred_rows]
    gt_coords, gt_labels = gt_coords[gt_rows], gt_labels[gt_rows]
    matches = MatchRows(pred_coords, gt_coords, shape)
    target = torch.zeros(len(pred_coords), device=pred_coords.device, dtype=torch.long)
    b_hit = matches >= 0
    target[b_hit] = gt_labels[matches[b_hit]]
    b_valid = target != 255
    confusion = torch.bincount(target[b_valid] * 4 + pred_labels[b_valid].long(), minlength=16).reshape(4, 4)
    # GT not covered by a prediction row is predicted empty; includes class errors
    # and all geometric coverage gaps, not only leaves generated by the decoder.
    reverse_matches = MatchRows(gt_coords, pred_coords, shape)
    b_missing = (reverse_matches < 0) & (gt_labels != 255)
    confusion[:, 0] += torch.bincount(gt_labels[b_missing], minlength=4)
    total_cells = int(grid_shape_xyz[0]) * int(grid_shape_xyz[1]) * int(grid_shape_xyz[2])
    ignored_count = int((gt_labels == 255).sum())
    accounted = int(b_valid.sum()) + int(b_missing.sum())
    confusion[0, 0] += total_cells - ignored_count - accounted
    tp = confusion.diagonal()
    fp, fn = confusion.sum(0) - tp, confusion.sum(1) - tp
    occupancy_tp = confusion[1:, 1:].sum()
    positive_gt = gt_coords[(gt_labels > 0) & (gt_labels < 4), 1:][:, [2, 1, 0]]
    statistics = {
        'confusion': confusion.cpu().tolist(),
        'tp': tp.cpu().tolist(), 'fp': fp.cpu().tolist(), 'fn': fn.cpu().tolist(),
        'occupancy_tp': int(occupancy_tp), 'occupancy_fp': int(confusion[0, 1:].sum()),
        'occupancy_fn': int(confusion[1:, 0].sum()),
        'gt_count': confusion.sum(1).cpu().tolist(), 'pred_count': confusion.sum(0).cpu().tolist(),
        'leaf_count': len(pred_coords), 'gt_positive_count': len(positive_gt),
    }
    if root_xyz is not None and kept_root_xyz is not None:
        b_before = CoverageMask(positive_gt, root_xyz, grid_shape_xyz, b_expand_roots)
        b_after = CoverageMask(positive_gt, kept_root_xyz, grid_shape_xyz, b_expand_roots)
        root_shape = tuple(v // 4 for v in shape)
        root_coords, kept_coords = BZYX(root_xyz), BZYX(kept_root_xyz)
        root_coords = root_coords[UniqueRows(root_coords, root_shape)]
        kept_coords = kept_coords[UniqueRows(kept_coords, root_shape)]
        positive_parents = BZYX(positive_gt // 4)
        b_positive = MatchRows(root_coords, positive_parents, root_shape) >= 0
        b_kept = MatchRows(root_coords, kept_coords, root_shape) >= 0
        statistics.update(
            reachable_gt=int(b_before.sum()), removed_gt=int((b_before & ~b_after).sum()),
            unreachable_gt=int((~b_before).sum()), covered_gt=int(b_after.sum()),
            root_count=len(root_coords), kept_root_count=len(kept_coords),
            deleted_root_count=int((~b_kept).sum()), occupied_root_count=int(b_positive.sum()),
            occupied_root_kept=int((b_positive & b_kept).sum()), occupied_root_deleted=int((b_positive & ~b_kept).sum()),
            empty_root_deleted=int((~b_positive & ~b_kept).sum()), empty_root_kept=int((~b_positive & b_kept).sum()))
    if b_collect_occ_stage_statistics:
        if any(value is None for value in (root_xyz, kept_root_xyz, current_points_xyz, pc_range, expanded_root_xyz, target_id)):
            raise ValueError('OCC stage statistics require roots, expanded roots, real current points, ROI and target ID')
        # Reuse the independently tested CPU accounting; only roots are expanded
        # for L+, never enumerate their millions of potential leaf coordinates.
        from occ_stage_statistics import FrameStatistics
        stage_started = time.perf_counter()
        stage = FrameStatistics(
            target_id=target_id, pred_xyz=pred_coords[:, 1:][:, [2, 1, 0]], pred_labels=pred_labels,
            gt_xyz=gt_coords[:, 1:][:, [2, 1, 0]], gt_labels=gt_labels, grid_shape_xyz=grid_shape_xyz,
            root_xyz=root_xyz, kept_root_xyz=kept_root_xyz, expanded_root_xyz=expanded_root_xyz,
            current_points_xyz=current_points_xyz, history_points_xyz=None,
            pc_range=pc_range, b_expand_roots=b_expand_roots,
            b_valid_roi_confirmed=b_valid_roi_confirmed,
        )
        for name in ('occupancy_tp', 'occupancy_fp', 'occupancy_fn'):
            if stage['counts'][name] != statistics[name]:
                raise AssertionError(f'Stage/full-ROI OCC count mismatch: {name}')
        if stage['counts']['full_confusion'] != statistics['confusion']:
            raise AssertionError('Stage/full-ROI OCC confusion mismatch')
        statistics['stages'] = stage
        statistics['stage_statistics_wall_seconds'] = time.perf_counter() - stage_started
    return statistics


def SummarizeMetrics(frame_statistics):
    """Aggregate already token-deduplicated frame stats; undefined ratios stay None."""
    frames = list(frame_statistics)
    if not frames:
        return {'frame_count': 0, 'occupancy_iou': None, 'semantic_miou': None, 'semantic_iou': [None] * 3}
    tp = torch.tensor([frame['tp'] for frame in frames], dtype=torch.long).sum(0)
    fp = torch.tensor([frame['fp'] for frame in frames], dtype=torch.long).sum(0)
    fn = torch.tensor([frame['fn'] for frame in frames], dtype=torch.long).sum(0)
    unions = tp + fp + fn
    semantic_iou = [float(tp[c] / unions[c]) if unions[c] else None for c in (1, 2, 3)]
    valid_iou = [value for value in semantic_iou if value is not None]
    totals = {name: sum(frame.get(name, 0) for frame in frames) for name in (
        'occupancy_tp', 'occupancy_fp', 'occupancy_fn', 'reachable_gt', 'removed_gt',
        'unreachable_gt', 'covered_gt', 'gt_positive_count', 'root_count', 'kept_root_count',
        'deleted_root_count', 'occupied_root_count', 'occupied_root_kept', 'occupied_root_deleted',
        'empty_root_deleted', 'empty_root_kept', 'leaf_count')}
    def Ratio(numerator, denominator):
        return totals[numerator] / totals[denominator] if totals[denominator] else None
    occupancy_union = totals['occupancy_tp'] + totals['occupancy_fp'] + totals['occupancy_fn']
    summary = dict(totals, frame_count=len(frames), tp=tp.tolist(), fp=fp.tolist(), fn=fn.tolist(),
                occupancy_iou=totals['occupancy_tp'] / occupancy_union if occupancy_union else None,
                semantic_iou=semantic_iou, semantic_miou=sum(valid_iou) / len(valid_iou) if valid_iou else None,
                valid_semantic_classes=[c for c, value in zip((1, 2, 3), semantic_iou) if value is not None],
                deletion_fraction=Ratio('deleted_root_count', 'root_count'),
                occupied_root_recall=Ratio('occupied_root_kept', 'occupied_root_count'),
                deletion_precision=Ratio('empty_root_deleted', 'deleted_root_count'),
                candidate_gt_coverage=Ratio('covered_gt', 'gt_positive_count'))
    summary['occupancy_precision'] = totals['occupancy_tp'] / (totals['occupancy_tp'] + totals['occupancy_fp']) if totals['occupancy_tp'] + totals['occupancy_fp'] else None
    summary['occupancy_recall'] = Ratio('occupancy_tp', 'gt_positive_count')
    summary['confusion'] = torch.tensor([frame['confusion'] for frame in frames], dtype=torch.long).sum(0).tolist()
    summary['gt_count'] = torch.tensor([frame['gt_count'] for frame in frames], dtype=torch.long).sum(0).tolist()
    summary['pred_count'] = torch.tensor([frame['pred_count'] for frame in frames], dtype=torch.long).sum(0).tolist()
    if any('root_diagnostics' in frame for frame in frames):
        if not all('root_diagnostics' in frame for frame in frames):
            raise ValueError('Mixed root diagnostic protocols in one validation')
        diagnostics = [frame['root_diagnostics'] for frame in frames]
        groups = {}
        for group in ('positive', 'empty'):
            prefix = f'root_{group}_'
            count = sum(frame[prefix + 'count'] for frame in diagnostics)
            metrics = sorted({key[len(prefix):-4] for frame in diagnostics for key in frame
                              if key.startswith(prefix) and key.endswith('_sum')})
            group_summary = {'count': count}
            for metric in metrics:
                total = sum(frame.get(prefix + metric + '_sum', 0.) for frame in diagnostics)
                group_summary[metric + '_sum'] = total
                group_summary[metric + '_mean'] = total / count if count else None
                maxima = [frame[prefix + metric + '_absmax'] for frame in diagnostics
                          if prefix + metric + '_absmax' in frame]
                if maxima:
                    group_summary[metric + '_absmax'] = max(maxima)
            groups[group] = group_summary
        summary['root_diagnostics'] = dict(groups=groups,
            aggregation='Additive sums divided by total group counts; p05/p50/p95 are per-frame only, not global quantiles',
            target_definition='0=own-root contains nonempty GT (keep), 1=own-root empty (delete)')
    b_stage_frames = ['stages' in frame for frame in frames]
    if any(b_stage_frames):
        if not all(b_stage_frames):
            raise ValueError('Mixed enabled/disabled OCC stage statistics in one validation')
        from occ_stage_statistics import StatisticsCollector
        collector = StatisticsCollector(b_enabled=True)
        for frame in frames:
            collector.Add(frame['stages'])
        if len(collector.frames) != len(frames):
            raise ValueError('Deduplicate validation target IDs before all-task aggregation')
        summary['stages'] = collector.Summary()
        summary['stages']['b_history_observation_collected'] = False
        durations = torch.tensor([frame['stage_statistics_wall_seconds'] for frame in frames], dtype=torch.float64)
        summary['stage_statistics_overhead'] = {
            'total_worker_seconds': float(durations.sum()), 'mean_per_target_seconds': float(durations.mean()),
            'p50_per_target_seconds': float(torch.quantile(durations, .5)),
            'p95_per_target_seconds': float(torch.quantile(durations, .95)),
            'scope': 'CPU stage accounting including device-to-host transfer; excluded from inference benchmark',
        }
    return summary
